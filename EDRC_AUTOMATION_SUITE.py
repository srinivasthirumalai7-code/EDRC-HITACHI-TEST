def _call(name):

    fn = _G.get(name)

    if callable(fn):
        try:
            _say("click  %s()" % name)
            fn()
            return True
        except Exception as exc:
            _say("%s() error: %s" % (name, exc))
    else:
        _say("button %s not found - skipping" % name)

    return False


def _begin_autorun(root):

    if _did_autorun[0]:
        return

    _did_autorun[0] = True

    if not _UNATTENDED:
        _say("attended mode - files pre-filled, waiting for you to click Start")
        return

    if not _profile:
        _say("no driver profile for %s - cannot auto-run" % _key)
        if _UNATTENDED:
            _say("walk-away is on - closing in 8s so the queue continues")
            root.after(8000, root.destroy)
        return

    list_fn, coords_fn, start_fn = _profile
    state = {"waited": 0}

    # IMPORTANT: load the LIST (TOC / RCC / etc.) FIRST, then coordinates.
    # Four of the programs refuse to load coordinates until their list is in
    # ("Please load ... first"), so coordinates-first silently loads nothing.
    def step_list():
        _call(list_fn)
        root.after(900, step_coords)

    def step_coords():
        _call(coords_fn)
        root.after(900, step_start)

    def step_start():
        _call(start_fn)
        root.after(600, check_started)

    def check_started():
        if _G.get(RUNNING_FLAG):
            _say("started - waiting for it to finish")
            root.after(1500, poll_done)
        else:
            state["waited"] += 1
            if state["waited"] * 500 >= 6000:
                _say("did not start within 6s (data not loaded?) - closing")
                root.after(300, root.destroy)
            else:
                root.after(500, check_started)

    def poll_done():
        if not _G.get(RUNNING_FLAG):
            _say("finished - closing window")
            root.after(1500, root.destroy)
        else:
            root.after(1500, poll_done)

    root.after(0, step_list)


_real_mainloop = tk.Misc.mainloop


