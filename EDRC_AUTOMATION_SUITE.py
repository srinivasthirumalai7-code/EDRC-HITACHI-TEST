    def start_run(self):

        if self.running:
            return

        if not self.selected:
            messagebox.showwarning("Nothing selected",
                                   "Tick at least one program first.")
            return

        missing = [k for k in self.selected if self.script_path(
            PROGRAM_BY_KEY[k]) is None]

        if missing:
            messagebox.showerror(
                "Script not found",
                "These programs have no script file:\n\n  %s\n\n"
                "Click the row to locate the .py file."
                % "\n  ".join(PROGRAM_BY_KEY[k]["name"] for k in missing))
            return

        # Warn about data files a program expects but which were not loaded.
        gaps = []

        for k in self.selected:
            for need in PROGRAM_BY_KEY[k]["needs"]:
                if not self.files.get(need):
                    label = next(s["label"] for s in DATA_SLOTS
                                 if s["key"] == need)
                    gaps.append("%s  needs  %s" % (PROGRAM_BY_KEY[k]["name"],
                                                   label))

        if gaps:
            proceed = messagebox.askyesno(
                "Data not loaded",
                "These files were not loaded in step 2:\n\n  %s\n\n"
                "Each program can still load its own files from its own "
                "window.\n\nStart the run anyway?" % "\n  ".join(gaps))

            if not proceed:
                return

        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")

        self.session_dir = REPORTS_ROOT / self.oem["code"] / ("SESSION_" + stamp)
        self.session_dir.mkdir(parents=True, exist_ok=True)

        self._write_autofeed_helper()

        self.results = {}
        self.claimed = set()
        self.running = True

        self.show_step(3)
        self.page_run.begin(list(self.selected))

        self._write_session()

        threading.Thread(target=self._run_queue,
                         args=(list(self.selected),), daemon=True).start()

    def _write_autofeed_helper(self):
        """(Re)writes the auto-feed helper next to the launcher so it always
        matches this version.  Silent if it cannot be written - the run then
        falls back to launching programs directly and each program simply
        asks for its files as before."""

        global AUTOFEED_HELPER

        try:
            with open(AUTOFEED_HELPER, "w", encoding="utf-8") as fh:
                fh.write(AUTOFEED_SOURCE)
        except Exception:
            pass

    def _run_queue(self, keys):
        """Runs every selected program one after another.  The next program
        only starts after the current one has closed and its report has been
        collected."""

        self.ui(self.page_run.log, "SESSION FOLDER  %s" % self.session_dir,
                "info")
        self.ui(self.page_run.log,
                "OEM  %s  -  %d PROGRAM(S) QUEUED" % (self.oem["code"],
                                                      len(keys)), "info")

        if AUTOFEED_HELPER.exists():
            if self.unattended:
                self.ui(self.page_run.log,
                        "WALK-AWAY MODE  -  each program is loaded, started, "
                        "and closed automatically. You can leave.", "info")
            else:
                self.ui(self.page_run.log,
                        "ATTENDED MODE  -  files are pre-filled; click START "
                        "inside each program, close it to advance.", "info")

        for position, key in enumerate(keys, start=1):

            if not self.running:
                break

            prog = PROGRAM_BY_KEY[key]
            script = self.script_path(prog)

            self.ui(self.page_run.mark, key, "RUNNING")
            self.ui(self.page_run.set_progress, position - 1, len(keys))
            self.ui(self.page_run.log, "", "plain")
            self.ui(self.page_run.log,
                    "[%d/%d]  STARTING  %s" % (position, len(keys),
                                               prog["name"]), "run")
            self.ui(self.page_run.log, "        %s" % script, "dim")

            if key == "SPL_CASE_CALLING_ON":
                feed = self.files.get("SPL_CASE")
                feed_label = "SPL CASE INPUT"
            else:
                feed = self.files.get("TOC")
                feed_label = "TOC"

            if feed:
                self.ui(self.page_run.log, "        LIST    <- %s  (%s)"
                        % (Path(feed).name, feed_label), "dim")

            if self.files.get("COORDS"):
                self.ui(self.page_run.log, "        COORDS  <- %s"
                        % Path(self.files["COORDS"]).name, "dim")

            started = time.time()

            log_handle = None

            try:
                env = os.environ.copy()
                env["EDRC_OEM"] = self.oem["code"]
                env["EDRC_SESSION_DIR"] = str(self.session_dir)
                env["EDRC_PROGRAM"] = key
                env["EDRC_UNATTENDED"] = "1" if self.unattended else "0"

                # Raw slot values, kept for reference / SESSION.json.
                for slot_key, path in self.files.items():
                    if path:
                        env["EDRC_" + slot_key] = str(path)

                # What the auto-feed helper actually hands to the program:
                #   the LIST dialog gets the SPL file for SPL case, else TOC;
                #   the COORDS dialog gets the coordinates file.
                if key == "SPL_CASE_CALLING_ON":
                    list_file = self.files.get("SPL_CASE")
                else:
                    list_file = self.files.get("TOC")

                coords_file = self.files.get("COORDS")

                if list_file:
                    env["EDRC_LIST"] = str(list_file)
                else:
                    env.pop("EDRC_LIST", None)

                if coords_file:
                    env["EDRC_COORDS"] = str(coords_file)
                else:
                    env.pop("EDRC_COORDS", None)

                # Tell the helper exactly which buttons to click for THIS
                # program, by key - so a renamed / moved .py still drives.
                drv = PROGRAM_DRIVERS.get(key)
                if drv:
                    env["EDRC_DRIVE_LIST"] = drv[0]
                    env["EDRC_DRIVE_COORDS"] = drv[1]
                    env["EDRC_DRIVE_START"] = drv[2]
                else:
                    for var in ("EDRC_DRIVE_LIST", "EDRC_DRIVE_COORDS",
                                "EDRC_DRIVE_START"):
                        env.pop(var, None)

                # A per-program folder + console log, created up front so the
                # run leaves an audit trail even for an overnight session.
                prog_folder = self.session_dir / ("%02d_%s" % (position,
                                                               prog["key"]))
                prog_folder.mkdir(parents=True, exist_ok=True)

                try:
                    log_handle = open(prog_folder / "console.log", "w",
                                      encoding="utf-8")
                except Exception:
                    log_handle = None

                self.proc = subprocess.Popen(
                    [sys.executable, str(AUTOFEED_HELPER), str(script)],
                    cwd=str(SCRIPT_DIR), env=env,
                    stdout=log_handle, stderr=subprocess.STDOUT)

                code = self.proc.wait()

            except Exception as exc:

                self.ui(self.page_run.log, "        LAUNCH FAILED  %s" % exc,
                        "fail")
                self.ui(self.page_run.mark, key, "FAILED")
                self.results[key] = {"status": "FAILED", "error": str(exc)}
                continue

            finally:
                self.proc = None
                if log_handle is not None:
                    try:
                        log_handle.close()
                    except Exception:
                        pass

            elapsed = int(time.time() - started)

            reports = self._collect_reports(prog, position, started)

            if not self.running:
                self.ui(self.page_run.mark, key, "STOPPED")
                self.results[key] = {"status": "STOPPED", "reports": reports}
                self.ui(self.page_run.log, "        STOPPED BY OPERATOR",
                        "fail")
                break

            if reports:
                for rep in reports:
                    self.ui(self.page_run.log, "        REPORT  %s"
                            % Path(rep).name, "ok")
                status = "COMPLETE"
            else:
                self.ui(self.page_run.log,
                        "        NO NEW REPORT FOUND FOR THIS PROGRAM", "warn")
                status = "NO REPORT"

            self.ui(self.page_run.log,
                    "        FINISHED  %s  (exit %s, %dm %02ds)"
                    % (prog["name"], code, elapsed // 60, elapsed % 60), "ok")

            self.ui(self.page_run.mark, key, status)

            self.results[key] = {
                "status": status,
                "exit_code": code,
                "seconds": elapsed,
                "reports": reports,
            }

            self.ui(self.page_run.set_progress, position, len(keys))

        self.running = False
        self._write_session()

        self.ui(self.page_run.finish)

    def _collect_reports(self, prog, position, since):
        """Copies any Excel report the program produced into the session
        folder.  Files are matched by the program's own report prefixes, and
        anything newer than the launch time is taken as a fallback."""

        folder = self.session_dir / ("%02d_%s" % (position, prog["key"]))

        found = []
        prefixes = [p.lower() for p in prog["reports"]]

        inputs = {str(Path(p).resolve()).lower()
                  for p in self.files.values() if p}

        try:
            candidates = list(SCRIPT_DIR.glob("*.xlsx"))
        except Exception:
            return found

        fresh = []

        for path in candidates:

            try:
                resolved = str(path.resolve()).lower()

                # Never pick up a data file, and never pick up a report that
                # an earlier program in this session already claimed.
                if resolved in inputs or resolved in self.claimed:
                    continue

                if path.stat().st_mtime < since - 2:
                    continue

                fresh.append(path)

            except Exception:
                continue

        # Prefer files whose name matches this program's own report prefix.
        # If the program was renamed, fall back to any unclaimed new file so
        # a report is collected rather than lost.
        matched = [p for p in fresh
                   if any(p.name.lower().startswith(pref) for pref in prefixes)]

        for path in (matched or fresh):

            try:
                folder.mkdir(parents=True, exist_ok=True)

                target = folder / path.name
                shutil.copy2(path, target)

                self.claimed.add(str(path.resolve()).lower())
                found.append(str(target))

            except Exception:
                continue

        return found

    def stop_run(self):

        if not self.running:
            return

        if not messagebox.askyesno(
                "Stop the run",
                "Stop after closing the program that is running now?\n\n"
                "The remaining programs in the queue will not start."):
            return

        self.running = False

        self.page_run.log("STOP REQUESTED BY OPERATOR", "fail")

        if self.proc and self.proc.poll() is None:
            try:
                self.proc.terminate()
            except Exception:
                pass

    def open_session_folder(self):

        if not self.session_dir or not Path(self.session_dir).exists():
            messagebox.showinfo("Reports", "No session folder yet.")
            return

        try:
            os.startfile(str(self.session_dir))
        except AttributeError:
            subprocess.Popen(["xdg-open", str(self.session_dir)])
        except Exception as exc:
            messagebox.showerror("Reports", str(exc))

    # =====================================================================
    #  PERSISTENCE
    # =====================================================================

    def _write_session(self):

        if not self.session_dir:
            return

        payload = {
            "oem": self.oem["code"] if self.oem else None,
            "created": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "data_files": {k: v for k, v in self.files.items() if v},
            "run_order": [PROGRAM_BY_KEY[k]["name"] for k in self.selected],
            "results": self.results,
        }

        try:
            with open(self.session_dir / "SESSION.json", "w",
                      encoding="utf-8") as fh:
                json.dump(payload, fh, indent=2)
        except Exception:
            pass

    def _load_suite_config(self):

        try:
            if SUITE_CONFIG.exists():
                with open(SUITE_CONFIG, "r", encoding="utf-8") as fh:
                    return json.load(fh)
        except Exception:
            pass

        return {}

    def _save_suite_config(self):

        try:
            with open(SUITE_CONFIG, "w", encoding="utf-8") as fh:
                json.dump(self.script_override, fh, indent=2)
        except Exception:
            pass

    # =====================================================================
    #  THREAD SAFE UI
    # =====================================================================

    def ui(self, fn, *args):
        """Marshals a call from the runner thread onto the tk main loop.

        Tk is not thread safe and calling after() straight from a worker
        thread is unreliable, so the call is parked on a queue that the
        main loop drains in _pump()."""

        self.ui_queue.put((fn, args))

    def _pump(self):
        """Drains anything the runner thread posted, then re-arms itself."""

        while True:
            try:
                fn, args = self.ui_queue.get_nowait()
            except queue.Empty:
                break

            try:
                fn(*args)
            except Exception as exc:
                print("UI update failed:", exc)

        self.after(60, self._pump)

    def on_close(self):

        if self.running:
            if not messagebox.askyesno(
                    "Run in progress",
                    "A program is still running. Close the suite anyway?"):
                return
            self.running = False

        self.destroy()


