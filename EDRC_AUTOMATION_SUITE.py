    def reattach_script(self, key):
        """Point a program row at a different .py file.  Works whether or not
        a file is already attached, so a wrong attachment can be corrected."""

        prog = PROGRAM_BY_KEY[key]

        current = self.script_path(prog)

        start_dir = str(current.parent) if current else str(SCRIPT_DIR)

        path = filedialog.askopenfilename(
            title="Attach a .py file for %s" % prog["name"],
            initialdir=start_dir,
            filetypes=[("Python", "*.py"), ("All Files", "*.*")])

        if not path:
            return

        chosen = Path(path).name

        # A gentle nudge if the file name looks unrelated to this program, but
        # the choice is still honoured - names may differ.
        if chosen.lower() != prog["script"].lower():
            if not messagebox.askyesno(
                    "Attach this file?",
                    "%s normally uses:\n    %s\n\nYou picked:\n    %s\n\n"
                    "Attach it to %s anyway?"
                    % (prog["name"], prog["script"], chosen, prog["name"])):
                return

        self.script_override[key] = path
        self._save_suite_config()
        self.page_prog.refresh()

        self.set_footer("ATTACHED  %s  ->  %s" % (prog["name"], chosen),
                        T.GREEN)

    def reset_script(self, key):
        """Drop a custom attachment and go back to the default file that sits
        next to the launcher (e.g. lock_route_automation_.py)."""

        prog = PROGRAM_BY_KEY[key]

        if key not in self.script_override:
            return

        default = SCRIPT_DIR / prog["script"]

        if messagebox.askyesno(
                "Reset to default",
                "Stop using the custom file and go back to:\n\n    %s\n\n"
                "%s"
                % (prog["script"],
                   "" if default.exists()
                   else "\n(Note: that file is not in the folder yet.)")):

            self.script_override.pop(key, None)
            self._save_suite_config()
            self.page_prog.refresh()

            self.set_footer("RESET  %s  ->  default (%s)"
                            % (prog["name"], prog["script"]), T.SLATE)

