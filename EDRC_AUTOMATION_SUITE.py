# --------------------------------------------------------------- helpers -----

def _bg_of(widget):
    try:
        return widget.cget("bg")
    except Exception:
        return T.BG


def _hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _rgb_to_hex(rgb):
    return "#%02x%02x%02x" % tuple(max(0, min(255, int(c))) for c in rgb)


def _shade(colour, amount):
    """amount < 0 darkens, amount > 0 lightens."""

    r, g, b = _hex_to_rgb(colour)

    if amount < 0:
        f = 1 + amount
        return _rgb_to_hex((r * f, g * f, b * f))

    return _rgb_to_hex((r + (255 - r) * amount,
                        g + (255 - g) * amount,
                        b + (255 - b) * amount))


def _mix(a, b, t):
    """t = 0 -> a,  t = 1 -> b"""

    ra, ga, ba = _hex_to_rgb(a)
    rb, gb, bb = _hex_to_rgb(b)

    return _rgb_to_hex((ra + (rb - ra) * t,
                        ga + (gb - ga) * t,
                        ba + (bb - ba) * t))


