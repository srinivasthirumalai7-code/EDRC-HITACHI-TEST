    def _find_recorder(self):
        """Locates the Universal Yard Coordinate Recorder.  Looks, in order:
        a remembered path, then next to the launcher, then in the same
        folder(s) as the attached test programs (so it's found even when the
        programs live elsewhere, e.g. Desktop\\AFAT FINAL).  Falls back to a
        loose name match so a slightly different file name still works."""

        # 1. remembered choice
        saved = self.script_override.get("RECORDER")
        if saved and Path(saved).exists():
            return saved

        # 2. build the list of folders to search
        search_dirs = [SCRIPT_DIR]

        for prog in PROGRAMS:
            sp = self.script_path(prog)
            if sp:
                search_dirs.append(sp.parent)

        for k, p in self.script_override.items():
            if k != "RECORDER" and p:
                search_dirs.append(Path(p).parent)

        # de-duplicate while preserving order
        seen = set()
        folders = []
        for d in search_dirs:
            d = Path(d)
            key = str(d).lower()
            if key not in seen and d.exists():
                seen.add(key)
                folders.append(d)

        # 3. exact known names first
        for d in folders:
            for name in RECORDER_CANDIDATES:
                cand = d / name
                if cand.exists():
                    return str(cand)

        # 4. loose match - any file that looks like the recorder
        patterns = ["*coordinate*recorder*.py", "*yard*coordinate*.py",
                    "*universal*yard*.py", "*recorder*.py"]
        for d in folders:
            for pat in patterns:
                for cand in sorted(d.glob(pat)):
                    return str(cand)

        return None

