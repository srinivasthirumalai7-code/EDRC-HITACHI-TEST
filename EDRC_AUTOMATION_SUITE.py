    def _resize_bar(self, event):

        self.bar.coords(self.bar_bg, 0, 0, event.width, 10)
        self._bar_width = event.width
        self._draw_bar()

    def _draw_bar(self):

        width = getattr(self, "_bar_width", 400)
        done = getattr(self, "_done", 0)
        total = max(1, getattr(self, "_total", 1))

        self.bar.coords(self.bar_fg, 0, 0, width * (done / total), 10)

    def set_progress(self, done, total):

        self._done, self._total = done, total
        self._draw_bar()

        self.progress_lab.config(
            text="%d of %d programs complete" % (done, total),
            fg=T.GREEN if done == total else T.TEXT_SOFT)

    # ------------------------------------------------------------------

    def begin(self, keys):

        for child in self.queue_holder.winfo_children():
            child.destroy()

        self.queue_rows = {}

        self.log_text.config(state="normal")
        self.log_text.delete("1.0", "end")
        self.log_text.config(state="disabled")

        for i, key in enumerate(keys, start=1):

            prog = PROGRAM_BY_KEY[key]

            row = tk.Frame(self.queue_holder, bg=T.CARD)
            row.pack(fill="x", padx=8, pady=5)

            lamp = Lamp(row, d=15, colour=T.GREY, bg=T.CARD)
            lamp.pack(side="left", padx=(4, 10))

            text = tk.Frame(row, bg=T.CARD)
            text.pack(side="left", fill="x", expand=True)

            tk.Label(text, text="%02d   %s" % (i, prog["name"]), bg=T.CARD,
                     fg=T.TEXT, font=T.f(12, "bold")).pack(anchor="w")

            state = tk.Label(text, text="WAITING", bg=T.CARD, fg=T.TEXT_SOFT,
                             font=T.mono(9))
            state.pack(anchor="w")

            self.queue_rows[key] = (lamp, state)

        self.set_progress(0, len(keys))
        self.stop_btn.set_enabled(True)
        self.back_btn.set_enabled(False)

        self.app.set_footer("RUN IN PROGRESS  -  DO NOT USE THE YARD TERMINAL",
                            T.AMBER)

    def mark(self, key, status):

        if key not in self.queue_rows:
            return

        lamp, state = self.queue_rows[key]

        colours = {
            "WAITING": (T.GREY, T.TEXT_SOFT),
            "RUNNING": (T.AMBER, T.AMBER),
            "COMPLETE": (T.GREEN, T.GREEN),
            "NO REPORT": (T.AMBER, T.AMBER),
            "STOPPED": (T.RED, T.RED),
            "FAILED": (T.RED, T.RED),
        }

        lamp_colour, text_colour = colours.get(status, (T.GREY, T.TEXT_SOFT))

        lamp.set(lamp_colour, lit=status != "WAITING")
        state.config(text=status, fg=text_colour)

    def log(self, message, tag="plain"):

        stamp = datetime.now().strftime("%H:%M:%S")
        line = ("%s  %s\n" % (stamp, message)) if message else "\n"

        self.log_text.config(state="normal")
        self.log_text.insert("end", line, tag)
        self.log_text.see("end")
        self.log_text.config(state="disabled")

    def finish(self):

        self.stop_btn.set_enabled(False)
        self.back_btn.set_enabled(True)

        done = sum(1 for r in self.app.results.values()
                   if r.get("status") == "COMPLETE")

        self.log("", "plain")
        self.log("SESSION FINISHED  -  %d COMPLETE, %d TOTAL"
                 % (done, len(self.app.results)), "ok")
        self.log("REPORTS  %s" % self.app.session_dir, "info")

        self.app.set_footer("SESSION FINISHED  -  REPORTS FILED IN %s"
                            % self.app.session_dir, T.GREEN)

        if self.app.session_dir and Path(self.app.session_dir).exists():
            try:
                os.startfile(str(self.app.session_dir))
            except Exception:
                pass

    def on_show(self):
        pass


