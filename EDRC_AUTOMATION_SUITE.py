class Lamp(tk.Canvas):
    """A signal aspect lamp.  Used for step progress and program status."""

    def __init__(self, parent, d=16, colour=T.GREY, bg=None, glow=True):

        bg = bg if bg is not None else _bg_of(parent)
        pad = 4 if glow else 1
        size = d + pad * 2

        super().__init__(parent, width=size, height=size, bg=bg,
                         highlightthickness=0, bd=0)

        self.glow_id = self.create_oval(1, 1, size - 1, size - 1,
                                        fill=bg, outline=bg) if glow else None

        self.bulb = self.create_oval(pad, pad, pad + d, pad + d,
                                     fill=colour, outline=_shade(colour, -0.2))

        self.bg = bg
        self.set(colour)

    def set(self, colour, lit=True):
        self.itemconfig(self.bulb, fill=colour,
                        outline=_shade(colour, -0.25))
        if self.glow_id is not None:
            halo = _mix(colour, self.bg, 0.72) if lit else self.bg
            self.itemconfig(self.glow_id, fill=halo, outline=halo)


class Toggle(tk.Canvas):
    """A compact on/off pill switch."""

    def __init__(self, parent, value=True, command=None, bg=None):

        bg = bg if bg is not None else _bg_of(parent)
        self.w, self.h = 52, 26

        super().__init__(parent, width=self.w, height=self.h, bg=bg,
                         highlightthickness=0, bd=0)

        self.value = value
        self.command = command

        self.track = rounded(self, 1, 1, self.w - 1, self.h - 1, 12,
                             fill=T.GREEN, outline=T.GREEN)

        self.knob = self.create_oval(0, 0, 0, 0, fill="white",
                                    outline="#E2E8F1")

        self.configure(cursor="hand2")
        self.bind("<Button-1>", self._flip)

        self._draw()

    def _draw(self):

        if self.value:
            self.itemconfig(self.track, fill=T.GREEN, outline=T.GREEN)
            x = self.w - self.h + 3
        else:
            self.itemconfig(self.track, fill="#B9C4D4", outline="#B9C4D4")
            x = 3

        self.coords(self.knob, x, 3, x + self.h - 6, self.h - 3)

    def _flip(self, _=None):
        self.value = not self.value
        self._draw()
        if self.command:
            self.command(self.value)

    def set(self, value):
        self.value = value
        self._draw()


